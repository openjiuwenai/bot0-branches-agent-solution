# coding: utf-8

"""影子任务的标识约定。

## 为什么在适配层的根，而不在领域层、也不在任一侧适配器内

**不在领域层**：它是键面约定——影子任务标识怎么拼、怎么认出来，属存储寻址细节，
不是领域概念。领域层的准入是「L1 权威定义的领域对象」，键面约定不在其列。

**不在任一侧适配器内**：它被进站与出站**共用**——进站按前缀拒绝客户端读取，
出站按同一前缀构造标识与筛选。放进任一侧，另一侧就要反向依赖它，那是同层横向依赖。

故落在适配层的根，与调用上下文构造点（`call_context.py`）同类：**跨适配器共用的构造点**。


## 为什么是领域概念

影子任务是远端批次的内部权威状态，其标识形态由数据架构视图的数据模型规定
（`shadow:{智能体标识}:{父任务标识}`），而非任一侧的实现细节。

**它被两个方向共用**：进站按前缀拒绝客户端读取，出站按同一前缀构造标识与筛选。
放在任一侧都会让另一侧反向依赖——那是同层横向依赖，两侧耦合在一个谁也不拥有的
约定上。放进领域层，两侧都向内依赖，方向干净。

**实证**：此前该常量落在进站层，出站的批次执行件跨包导入它。洋葱契约只守跨层方向，
同层横向它一句话不说，故该依赖长期存在而无人察觉。
"""
from __future__ import annotations

#: 影子任务的标识前缀。取自上游详设的键形态 `shadow:<智能体标识>:<父任务标识>`。
#:
#: **两侧不得各写一份字面量**：对外视图按它拒绝客户端读取、构造侧按它拼标识，
#: 各写一份时改一处忘另一处，会让影子任务静默变成客户端可见。
SHADOW_PREFIX = "shadow:"


def is_shadow(task_id: str) -> bool:
    """判定一个任务标识是否属于影子任务。

    以前缀判定而非查存储——判定必须在读取之前发生，否则等于先泄漏再补救。
    """
    return bool(task_id) and task_id.startswith(SHADOW_PREFIX)


def shadow_task_id(*, parent_task_id: str, agent_id: str) -> str:
    """构造影子任务标识。形态取自上游详设：`shadow:{智能体标识}:{父任务标识}`。

    **两个参数都是关键字参数**：签名的顺序（父任务在前）与拼接的顺序（智能体在前）
    相反，而两者都是 `str`——位置传参写反时不产生任何报错，只会静默构出一个
    错误的键，认领与筛选随之失配。改成关键字后，写反在语法上就不成立。
    """
    return f"{SHADOW_PREFIX}{agent_id}:{parent_task_id}"
