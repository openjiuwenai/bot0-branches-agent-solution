# coding: utf-8

"""协议库调用上下文的系统级构造（适配层共用）。

## 为什么需要它

协议库的任务存储与推送配置存储，每个方法都要一个调用上下文参数。而 runtime 有一类
操作**不来自任何一次调用**——异步回调认领、批次快照维护、终态推送投递，它们发生在
请求早已返回之后，没有现成的上下文可传。

此前这些地方一律传空值。协议库的存储实现会解引用它取属主，于是整条回调认领链路
对协议库存储直接抛错、异常被吞成一条告警，而判据全绿——判据用的替身把这个参数
写成了可选。

## 为什么放在适配层根下

它承载协议库类型，**不能下沉领域层**（领域层零协议依赖）。而进站与出站两侧都要用：
进站的终态推送、出站的批次维护。放进任一侧都会让另一侧反向依赖，那是同层横向依赖。
放在两个方向包之外，两侧都是向内依赖同一处。

## 属主由宿主在装配期决定，不由适配层硬编码

**上游的领域模型里没有「属主」这一维**：其任务存储接口是 `save(Task, boolean)` /
`get(String)` / `delete(String)` / `list(params)`，不带调用上下文。按属主分区是 Python
协议库的特性，不是 agent-runtime 的领域设计。我方的 Redis 存储同样按任务标识直接寻址、
不分区——与上游一致。

**但协议库把「后台组件在哪个属主下工作」定成了装配期的注入项**：它的推送发送器
构造签名第三个参数就是调用上下文，文档写明「本次推送在哪个上下文下产生」
（`a2a/server/tasks/base_push_notification_sender.py`）。

故本模块只提供**默认值**（未认证形态，属主为空串），实际取值由宿主经装配函数注入。
此前在适配层硬编码恒空属主并把后果写进注释当残余风险——那是把协议库的属主维度
当成了可以填空值的形式参数。独立验证实测出后果：宿主启用认证后，终态推送读不到
请求链路写入的配置，投递整条断且**没有任何错误信号**（读到空配置即直接返回）。
"""
from __future__ import annotations

from a2a.server.context import ServerCallContext
from a2a.types.a2a_pb2 import ListTasksRequest


def system_call_context() -> ServerCallContext:
    """构造一次**默认**的系统级调用上下文（未认证形态）。

    **这是默认值，不是唯一取值**：开了认证的宿主须在装配期注入自己的上下文，
    否则后台操作与请求链路落在不同属主分区上。装配函数的相应参数即为此设。

    **每次新建而非复用单例**：该对象带一个可变的状态字典，多处共用会让互不相干的
    操作互相污染。构造代价可忽略。
    """
    return ServerCallContext()


#: 协议库允许的单页上限。取上限是为了少翻几页，不是为了省略翻页。
MAX_PAGE_SIZE = 100


def list_all_request(page_token: str = "", *, tenant: str = "") -> ListTasksRequest:
    """构造「不加过滤、按最大页取一页」的列表请求。

    协议库的列表方法按字段是否非空决定过不过滤，空对象即全量。**不能传空值**——
    实现会直接取它的字段，传空值当场抛属性错误。

    **页大小取上限、并须由调用方翻完所有页**：不指定时协议库按默认页大小截断，
    独立验证实测过——存储里任务多于一页时，要找的目标被挤出首页，调用方却看到
    一个「正常返回」的结果。分页截断是静默的，比报错危险。

    参数 tenant：租户标识，进协议库列举参数的同名字段。**对齐上游形态**——
    上游把它放在列举参数上（其自定义 REST 的任务检索件构造列举参数时带 `.tenant(...)`），
    而不是拼进键名。

    **这条路不碰与存量共享的键面**：租户若进键名，就改动了被黄金基线冻结为对外契约的
    那批键，与「对外兼容」直接冲突；进列举参数则是查询侧的过滤条件，对外键面一字未改。
    按用户裁定「存量兼容优先」，取后者。

    **已知边界**：协议库自带的存储与上游的存储实现**都不按该字段过滤**——
    租户在上游同样是「传下去了、存储层没消费」的状态。故本参数当前是**语义占位**：
    它让隔离条件随调用链传到存储层，实际过滤由存储实现决定。
    我方的存储实现是否消费它，另行裁定，不在本次改动范围。
    """
    return ListTasksRequest(page_size=MAX_PAGE_SIZE, page_token=page_token, tenant=tenant)


__all__ = ["MAX_PAGE_SIZE", "system_call_context", "list_all_request"]
