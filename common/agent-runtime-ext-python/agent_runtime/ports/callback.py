"""异步回调的回灌端口（洋葱内圈，零框架依赖）。

## 它是什么

回调**经过接收器的校验与幂等判重之后**的处置面。接收器负责鉴权、受信来源校验、
判重与本地关联四步；本端口只做最后一件事——把这个回调绑定到本地可恢复的状态上。

对齐上游同名接口：单方法、返回是否绑定成功
（`openJiuwen/agent-runtime-java` 的 `A2aPushNotificationCallbackHandler.onAccepted`，
其文档写明「处理接收器校验与幂等检查之后首次见到的回调」「返回是否绑定到了本地可恢复状态」）。

## 为什么立成独立端口，而不是挂在批次执行件上

此前这个能力挂在批次执行件上，且**端口没有声明它**——装配处靠属性探测判断有没有。
后果有两层：按端口写出来的批次执行件在回调这条路径上静默失能；而「有没有这个能力」
这件事只能靠探测得知，探测成功不等于能力可用。

上游把它立成独立接口，与批次执行无关——回灌的落点未必是批次（也可能是等待中的
单次调用、或别的可恢复状态）。**能力独立，端口就该独立。**

## 返回值的含义

`True` 表示这个回调**确实绑定到了某个本地状态**；`False` 表示没有匹配的绑定。
上游据此让接收端点返回「绑定未找到」而非成功——调用方因此知道这次投递没有落点，
而不是以为已经处理。
"""
from __future__ import annotations

from typing import Any, Protocol, runtime_checkable


@runtime_checkable
class CallbackBackfiller(Protocol):
    """回调回灌面。实现方把回调绑定到本地可恢复状态。"""

    async def claim_callback(self, remote_task_id: str, payload: Any) -> bool:
        """认领一个已通过校验与判重的回调。

        参数 remote_task_id：回调关联的远端任务标识，由接收器从载荷定位后传入。
        参数 payload：回调载荷。**本层不解析其业务内容**——它是远端产出的结果表面，
            语义归产生它的那一方。

        返回：是否绑定到了本地可恢复状态。**没有匹配的绑定时返回假，不要返回真**——
        调用方据此如实告知投递方，而报真会让投递方停止重试，结果永久丢失。
        """
